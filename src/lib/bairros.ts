const ABREVIACOES: Record<string, string> = {
  jd: 'jardim',
  jdm: 'jardim',
  res: 'residencial',
  resid: 'residencial',
  conj: 'conjunto',
  cj: 'conjunto',
  pq: 'parque',
  vl: 'vila',
  hab: 'habitacional',
  lot: 'loteamento',
  sta: 'santa',
  sto: 'santo',
}

const ROMANOS: Record<string, string> = { '1': 'i', '2': 'ii', '3': 'iii', '4': 'iv', '5': 'v' }

/** Chave que ignora acentos, maiúsculas, apóstrofos, pontuação, abreviações e "3" × "III" */
export function chaveBairro(bairro: string): string {
  return bairro
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .replace(/['’`´]/g, '')
    .replace(/[^a-z0-9]+/g, ' ')
    .trim()
    .replace(/\bd (?=[a-z])/g, 'd') // "olho d agua" = "olho dagua"
    .replace(/^bairro\s+/, '')
    .split(' ')
    .map(palavra => ABREVIACOES[palavra] ?? ROMANOS[palavra] ?? palavra)
    .join(' ')
}

const OFICIAIS: Record<string, Record<string, string>> = Object.fromEntries(
  Object.entries(BAIRROS_POR_CIDADE).map(([cidade, bairros]) => [
    cidade,
    Object.fromEntries(bairros.map(nome => [chaveBairro(nome), nome])),
  ])
)

/** Nome oficial do bairro na cidade, ou undefined se a cidade tem lista e o bairro não está nela */
export function bairroOficial(cidade: string, bairro: string): string | undefined {
  return OFICIAIS[cidade]?.[chaveBairro(bairro)]
}

/** Nome oficial em qualquer cidade com lista (para dados antigos, em que a cidade pode estar escrita de outro jeito) */
export function bairroOficialQualquer(bairro: string): string | undefined {
  const chave = chaveBairro(bairro)
  for (const nomes of Object.values(OFICIAIS)) if (nomes[chave]) return nomes[chave]
  return undefined
}
